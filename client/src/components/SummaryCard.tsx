import { Check, Copy, FileText } from "lucide-react";
import { useEffect, useState } from "react";
import { copyText } from "../lib/clipboard";
import type { Panel, SummaryPayload } from "../types";
import { EmptyState } from "./EmptyState";
import { ErrorMessage } from "./ErrorMessage";
import { LoadingState } from "./LoadingState";
import { btnSecondary, card } from "./ui";

type Block = { type: "p"; text: string } | { type: "ul"; items: string[] };

function toBlocks(text: string): Block[] {
  const blocks: Block[] = [];
  for (const raw of text.split("\n")) {
    const line = raw.trim();
    if (!line) continue;
    const bullet = /^[-•*]\s+(.*)$/.exec(line);
    if (bullet) {
      const last = blocks[blocks.length - 1];
      if (last && last.type === "ul") last.items.push(bullet[1]);
      else blocks.push({ type: "ul", items: [bullet[1]] });
    } else {
      blocks.push({ type: "p", text: line });
    }
  }
  return blocks;
}

export function SummaryCard({ panel, model }: { panel: Panel<SummaryPayload>; model: string }) {
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    if (!copied) return;
    const t = window.setTimeout(() => setCopied(false), 2000);
    return () => window.clearTimeout(t);
  }, [copied]);

  async function handleCopy() {
    if (!panel.data) return;
    setCopied(await copyText(panel.data.text));
  }

  return (
    <section className={`${card} p-5 sm:p-6`} aria-labelledby="summary-heading">
      <div className="flex items-center justify-between gap-3">
        <h2 id="summary-heading" className="flex items-center gap-3 font-display text-lg font-bold tracking-tight text-ink">
          <span className="flex h-9 w-9 items-center justify-center rounded-xl bg-lilac text-violet">
            <FileText className="h-5 w-5" aria-hidden="true" />
          </span>
          Summary
        </h2>
        {panel.status === "success" && panel.data ? (
          <button type="button" className={btnSecondary} onClick={handleCopy}>
            {copied ? <Check className="h-4 w-4 text-emerald-700" aria-hidden="true" /> : <Copy className="h-4 w-4" aria-hidden="true" />}
            {copied ? "Copied" : "Copy summary"}
          </button>
        ) : null}
      </div>

      <div className="mt-4">
        {panel.status === "idle" && (
          <EmptyState
            icon={<FileText className="h-5 w-5" aria-hidden="true" />}
            title="No summary yet"
            description="Paste your study material and choose Generate. Your summary will appear here."
          />
        )}

        {panel.status === "loading" && (
          <LoadingState
            message={`Summarising with ${model}…`}
            detail="The hosted model usually answers within a few seconds."
          />
        )}

        {panel.status === "error" && <ErrorMessage title="Could not generate the summary" message={panel.error ?? "Unknown error."} />}

        {panel.status === "success" && panel.data && (
          <div>
            <div className="max-w-prose space-y-3.5 text-base leading-7 text-ink">
              {toBlocks(panel.data.text).map((block, i) =>
                block.type === "p" ? (
                  <p key={i}>{block.text}</p>
                ) : (
                  <ul key={i} className="list-disc space-y-2 pl-5 marker:text-coral">
                    {block.items.map((item, j) => (
                      <li key={j}>{item}</li>
                    ))}
                  </ul>
                ),
              )}
            </div>
            <p className="mt-6 border-t border-line pt-3 text-xs text-muted">
              Generated by {panel.data.meta.model} in {(panel.data.meta.durationMs / 1000).toFixed(1)}s
              {panel.data.meta.outputTokens !== null ? ` (${panel.data.meta.outputTokens} tokens)` : ""}. AI output can contain
              mistakes, so check important facts against your source.
            </p>
          </div>
        )}
      </div>
    </section>
  );
}
